String? canonicalIgdbPlatform(String romgiPlatform) {
  final id = romgiPlatform.toLowerCase();
  final catalog = igdbPlatformAliases[id] ?? id;
  if (igdbPlatformIds.containsKey(catalog)) return catalog;
  return null;
}
